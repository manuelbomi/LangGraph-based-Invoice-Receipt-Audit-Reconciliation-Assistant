def seed() -> None:
    with SessionLocal() as db:
        for build in (
            build_clean_match_run,
            build_duplicate_payment_run,
            build_over_threshold_run,
            build_no_match_run,
        ):
            run = build()
            existing = db.get(Run, run.id)
            if existing is None:
                db.add(run)
        db.commit()
    print("Seeded 4 example runs.")


if __name__ == "__main__":
    seed()
