"""Seed 4 realistic, complete example runs into the `runs` table, using the
bundled synthetic sample documents (see `sample-data/README.md`).

These are hand-authored (not generated by a live LLM call, to keep this
repo's setup free to run) but are coherent, realistic end-to-end traces of
exactly what the graph produces: extracted fields, validation issues,
reconciliation findings (including the headline duplicate-payment catch),
a human decision, and a final status. They exist so the "Run History /
Example Analyses" page has real, varied content to show a visitor before
they run anything themselves.

Run with:
    python -m scripts.seed_examples

Requires the sample ledger to already be loaded (`scripts/seed_ledger.py`)
so the reconciliation findings below match what the live graph would
actually produce against it.
"""
from __future__ import annotations

from datetime import datetime, timedelta, timezone

from app.db.models import Run
from app.db.session import SessionLocal

# Fixed (not random) ids so re-running this script is genuinely idempotent
# -- e.g. every container start in docker-entrypoint.sh -- instead of
# accumulating a fresh set of duplicate example runs each time.
