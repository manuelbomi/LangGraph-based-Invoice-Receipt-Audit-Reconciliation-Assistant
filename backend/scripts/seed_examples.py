def _iso(dt: datetime) -> str:
    return dt.isoformat()


def _trace(base: datetime, node: str, minutes: float, summary: str) -> dict:
    return {"node": node, "timestamp": _iso(base + timedelta(minutes=minutes)), "summary": summary}


def _line_item(description: str, quantity: float, unit_price: float, amount: float) -> dict:
    return {"description": description, "quantity": quantity, "unit_price": unit_price, "amount": amount}


